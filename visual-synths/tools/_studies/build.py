#!/usr/bin/env python3
"""Assemble visual-synths/<slug>.html from tools/_studies/<slug>.src.html.

Source format: first line is JSON meta {"title", "desc"}; the rest is the page body
(hero, stage, controls, about) ending with the piece's own <script>. The builder adds the
shared head (chrome CSS), header, footer and the GL kit + kit extras before the first <script>.
Run: python3 visual-synths/tools/_studies/build.py [slug ...]
"""
import json, os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'engine'))
from ga import apply as ga_apply   # the Google Analytics tag (engine/ga.py)
OUT = os.path.abspath(os.path.join(HERE, '..', '..'))
css = open(os.path.join(HERE, '_chrome.css')).read()
kit = open(os.path.join(HERE, '_kit.js')).read()
kitx = open(os.path.join(HERE, '_kitx.js')).read()
TOKEN = 'bba4e16a7d9b4d9985eda0cda2624e60'

def page(slug):
    src = open(os.path.join(HERE, slug + '.src.html')).read()
    first, body = src.split('\n', 1)
    meta = json.loads(first)
    t, d = meta['title'], meta['desc']
    url = 'https://followorbounce.github.io/visual-synths/' + slug
    esc = lambda s: s.replace('&', '&amp;').replace('"', '&quot;')
    head = f'''<!DOCTYPE html>
<html lang="en">
<head>
<script async src="https://www.googletagmanager.com/gtag/js?id=G-CE86H6X7Z7"></script>
<script>
  window.dataLayer = window.dataLayer || [];
  function gtag(){{dataLayer.push(arguments);}}
  gtag('js', new Date());
  gtag('config', 'G-CE86H6X7Z7');
</script>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<title>{t} — Video Synths</title>
<meta name="description" content="{esc(d)}">
<link rel="canonical" href="{url}">
<meta name="theme-color" content="#F4F4F1">
<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
<meta property="og:type" content="website">
<meta property="og:title" content="{t} — Video Synths">
<meta property="og:description" content="{esc(d)}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{url.replace(".io/", ".io/og/")}.jpg">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{t} — Video Synths">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:image" content="{url.replace(".io/", ".io/og/")}.jpg">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600;700&family=Manrope:wght@500;600;700;800&display=swap" rel="stylesheet">
<script src="/assets/theme-toggle.js"></script>
<style>
{css}
</style>
<script defer src="https://static.cloudflareinsights.com/beacon.min.js" data-cf-beacon='{{"token": "{TOKEN}"}}'></script>
</head>
<body>
<!-- generated by visual-synths/tools/_studies/build.py from {slug}.src.html — edit the source, not this file -->

<header>
  <div class="wrap">
    <a class="brand" href="/">KNOWLEDGE NETWORK</a>
    <a class="back" href="/visual-synths/">← Video Synths</a>
  </div>
</header>
'''
    foot = '''
<footer>
  <div class="wrap">
    <span>KNOWLEDGE NETWORK — followorbounce.github.io — <a href="/">Index</a> · <a href="/visual-synths/">Video Synths</a></span>
  </div>
</footer>
'''
    i = body.index('<script>')
    html = head + body[:i] + foot + '\n<script>\n' + kit + '\n' + kitx + '\n</script>\n' + body[i:].rstrip() + '\n</body>\n</html>\n'
    open(os.path.join(OUT, slug + '.html'), 'w').write(ga_apply(html))
    print('wrote', slug + '.html', len(html))

slugs = sys.argv[1:] or sorted(f[:-9] for f in os.listdir(HERE) if f.endswith('.src.html'))
for s in slugs: page(s)
